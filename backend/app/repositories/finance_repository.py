"""Database repository supporting local SQLite and configured MySQL."""

from __future__ import annotations

import os
from contextlib import contextmanager
from datetime import date
from functools import lru_cache
from pathlib import Path
from typing import Any, Iterator

from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import Connection, Engine

from app.config import DB_PATH, DEFAULT_CATEGORIES

SEED_BUDGETS = (("Makan", 500_000), ("Transport", 200_000), ("Hiburan", 150_000), ("Kos", 500_000))


def _database_url() -> str:
    url = os.getenv("DATABASE_URL")
    if not url:
        return f"sqlite:///{Path(DB_PATH).resolve()}"
    if url.startswith("postgres://"):
        return "postgresql+psycopg://" + url.removeprefix("postgres://")
    if url.startswith("postgresql://"):
        return "postgresql+psycopg://" + url.removeprefix("postgresql://")
    return url


@lru_cache(maxsize=8)
def _engine_for(url: str) -> Engine:
    connect_args: dict[str, Any] = {}
    engine_options: dict[str, Any] = {"future": True, "pool_pre_ping": True}
    if url.startswith("sqlite"):
        connect_args["check_same_thread"] = False
    elif url.startswith("postgresql"):
        # Supabase transaction pooler is intended for serverless and does not
        # support persistent prepared statements. Keep each warm function's
        # client pool small and require TLS.
        connect_args.update({"sslmode": "require", "prepare_threshold": None})
        engine_options.update({"pool_size": 1, "max_overflow": 0, "pool_recycle": 300})
    elif url.startswith("mysql"):
        engine_options.update({"pool_size": 1, "max_overflow": 0, "pool_recycle": 300})
    return create_engine(url, connect_args=connect_args, **engine_options)


@contextmanager
def get_connection() -> Iterator[Connection]:
    """Yield a transactional SQLAlchemy connection and always release it."""
    with _engine_for(_database_url()).begin() as connection:
        yield connection


def init_db(*, seed: bool = False) -> None:
    """Create tables and add ownership columns to a pre-account SQLite database."""
    dialect = _engine_for(_database_url()).dialect.name
    is_sqlite = dialect == "sqlite"
    is_postgresql = dialect == "postgresql"
    if dialect not in {"sqlite", "mysql", "postgresql"}:
        raise RuntimeError(f"Unsupported database dialect: {dialect}")
    if is_sqlite:
        identity = "INTEGER PRIMARY KEY AUTOINCREMENT"
        amount_type, timestamp_type, timestamp_default = "REAL", "TEXT", "datetime('now', 'localtime')"
        description_type, avatar_type = "TEXT", "BLOB"
    elif is_postgresql:
        identity = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        amount_type, timestamp_type, timestamp_default = "NUMERIC(15, 2)", "TIMESTAMP WITH TIME ZONE", "CURRENT_TIMESTAMP"
        description_type, avatar_type = "TEXT", "BYTEA"
    else:
        identity = "INTEGER PRIMARY KEY AUTO_INCREMENT"
        amount_type, timestamp_type, timestamp_default = "DECIMAL(15, 2)", "TIMESTAMP", "CURRENT_TIMESTAMP"
        description_type, avatar_type = "VARCHAR(1000)", "MEDIUMBLOB"
    timestamp_default_clause = (
        f"DEFAULT ({timestamp_default})" if is_sqlite else f"DEFAULT {timestamp_default}"
    )

    with get_connection() as conn:
        if is_postgresql:
            # Avoid simultaneous cold-start schema upgrades across serverless
            # instances. This transaction-scoped lock is released automatically.
            conn.execute(text("SELECT pg_advisory_xact_lock(781245901)"))
        conn.execute(text(f"""
            CREATE TABLE IF NOT EXISTS users (
                id {identity}, name VARCHAR(100) NOT NULL,
                email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
                theme VARCHAR(10) NOT NULL DEFAULT 'light',
                avatar_blob {avatar_type} NULL,
                avatar_content_type VARCHAR(50) NULL,
                created_at {timestamp_type} NOT NULL {timestamp_default_clause}
            )
        """))
        conn.execute(text(f"""
            CREATE TABLE IF NOT EXISTS transactions (
                id {identity}, user_id INTEGER NULL,
                type VARCHAR(10) NOT NULL CHECK(type IN ('income', 'expense')),
                amount {amount_type} NOT NULL CHECK(amount > 0),
                category VARCHAR(100) NOT NULL, description {description_type} NOT NULL DEFAULT '',
                date VARCHAR(10) NOT NULL,
                created_at {timestamp_type} NOT NULL {timestamp_default_clause},
                FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            )
        """))
        conn.execute(text(f"""
            CREATE TABLE IF NOT EXISTS budgets (
                id {identity}, user_id INTEGER NULL, category VARCHAR(100) NOT NULL,
                monthly_limit {amount_type} NOT NULL CHECK(monthly_limit > 0),
                created_at {timestamp_type} NOT NULL {timestamp_default_clause},
                FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                CONSTRAINT uq_budgets_user_category UNIQUE(user_id, category)
            )
        """))
        inspector = inspect(conn)
        user_columns = {column["name"] for column in inspector.get_columns("users")}
        if "theme" not in user_columns:
            conn.execute(text("ALTER TABLE users ADD COLUMN theme VARCHAR(10) NOT NULL DEFAULT 'light'"))
        if "avatar_blob" not in user_columns:
            conn.execute(text(f"ALTER TABLE users ADD COLUMN avatar_blob {avatar_type} NULL"))
        if "avatar_content_type" not in user_columns:
            conn.execute(text("ALTER TABLE users ADD COLUMN avatar_content_type VARCHAR(50) NULL"))
        if "user_id" not in {column["name"] for column in inspector.get_columns("transactions")}:
            conn.execute(text("ALTER TABLE transactions ADD COLUMN user_id INTEGER NULL"))
        if "user_id" not in {column["name"] for column in inspector.get_columns("budgets")}:
            conn.execute(text("ALTER TABLE budgets ADD COLUMN user_id INTEGER NULL"))
        if is_sqlite:
            _migrate_legacy_sqlite_budgets(conn)
        elif is_postgresql:
            _migrate_legacy_postgresql_budgets(conn)
            for table in ("users", "transactions", "budgets"):
                conn.execute(text(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY'))
        else:
            _migrate_legacy_mysql_budget_uniqueness(conn)
        if seed:
            _seed_if_empty(conn)


def _migrate_legacy_sqlite_budgets(conn: Connection) -> None:
    indexes = conn.execute(text("PRAGMA index_list('budgets')")).mappings().all()
    for index in indexes:
        if index["unique"]:
            columns = conn.execute(text(f"PRAGMA index_info('{index['name']}')")).mappings().all()
            if [column["name"] for column in columns] == ["category"]:
                conn.execute(text("""
                    CREATE TABLE budgets_new (
                        id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NULL,
                        category VARCHAR(100) NOT NULL, monthly_limit REAL NOT NULL CHECK(monthly_limit > 0),
                        created_at TEXT NOT NULL DEFAULT (datetime('now', 'localtime')),
                        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                        CONSTRAINT uq_budgets_user_category UNIQUE(user_id, category)
                    )
                """))
                conn.execute(text("INSERT INTO budgets_new (id, user_id, category, monthly_limit, created_at) SELECT id, user_id, category, monthly_limit, created_at FROM budgets"))
                conn.execute(text("DROP TABLE budgets"))
                conn.execute(text("ALTER TABLE budgets_new RENAME TO budgets"))
                return
    conn.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS uq_budgets_user_category ON budgets(user_id, category)"))


def _migrate_legacy_mysql_budget_uniqueness(conn: Connection) -> None:
    inspector = inspect(conn)
    has_owner_unique = any(
        item.get("column_names") == ["user_id", "category"]
        for item in inspector.get_unique_constraints("budgets")
    )
    for constraint in inspector.get_unique_constraints("budgets"):
        if constraint.get("column_names") == ["category"]:
            name = constraint["name"].replace("`", "``")
            conn.execute(text(f"ALTER TABLE budgets DROP INDEX `{name}`"))
    if not has_owner_unique and conn.dialect.name == "mysql":
        conn.execute(text("CREATE UNIQUE INDEX uq_budgets_user_category ON budgets(user_id, category)"))


def _migrate_legacy_postgresql_budgets(conn: Connection) -> None:
    inspector = inspect(conn)
    has_owner_unique = any(
        item.get("column_names") == ["user_id", "category"]
        for item in inspector.get_unique_constraints("budgets")
    )
    for constraint in inspector.get_unique_constraints("budgets"):
        if constraint.get("column_names") == ["category"]:
            name = constraint["name"].replace('"', '""')
            conn.execute(text(f'ALTER TABLE budgets DROP CONSTRAINT "{name}"'))
    if not has_owner_unique:
        conn.execute(text(
            "CREATE UNIQUE INDEX IF NOT EXISTS uq_budgets_user_category "
            "ON budgets(user_id, category)"
        ))


def _seed_if_empty(conn: Connection) -> None:
    # Explicit development-only seed; normal startup does not create unowned data.
    ym = date.today().strftime("%Y-%m")
    samples = [
        ("income", 2_000_000, "Beasiswa", "Pencairan beasiswa semester ini", f"{ym}-01"),
        ("expense", 450_000, "Kos", "Sewa kos bulan ini", f"{ym}-02"),
        ("expense", 250_000, "Makan", "Belanja makan minggu 1", f"{ym}-05"),
        ("expense", 150_000, "Transport", "Ojek & angkot", f"{ym}-07"),
        ("expense", 200_000, "Kuliah", "Fotokopi & alat tulis", f"{ym}-08"),
        ("expense", 100_000, "Hiburan", "Nonton & kopi", f"{ym}-09"),
    ]
    if conn.execute(text("SELECT COUNT(*) FROM transactions")).scalar_one() == 0:
        conn.execute(text("INSERT INTO transactions (user_id, type, amount, category, description, date) VALUES (NULL, :type, :amount, :category, :description, :date)"), [dict(zip(("type", "amount", "category", "description", "date"), row)) for row in samples])
    if conn.execute(text("SELECT COUNT(*) FROM budgets")).scalar_one() == 0:
        conn.execute(text("INSERT INTO budgets (user_id, category, monthly_limit) VALUES (NULL, :category, :limit)"), [{"category": category, "limit": amount} for category, amount in SEED_BUDGETS])


def create_user(*, name: str, email: str, password_hash: str) -> int:
    with get_connection() as conn:
        statement = "INSERT INTO users (name, email, password_hash) VALUES (:name, :email, :password_hash)"
        if conn.dialect.name == "postgresql":
            result = conn.execute(text(statement + " RETURNING id"), {"name": name, "email": email, "password_hash": password_hash})
            user_id = int(result.scalar_one())
        else:
            result = conn.execute(text(statement), {"name": name, "email": email, "password_hash": password_hash})
            user_id = int(result.lastrowid)
        # The first account claims rows left by the former single-user SQLite app.
        conn.execute(text("UPDATE transactions SET user_id = :user_id WHERE user_id IS NULL"), {"user_id": user_id})
        conn.execute(text("UPDATE budgets SET user_id = :user_id WHERE user_id IS NULL"), {"user_id": user_id})
        return user_id


def get_user_by_email(email: str) -> dict[str, Any] | None:
    with get_connection() as conn:
        row = conn.execute(text("SELECT id, name, email, password_hash, theme, CASE WHEN avatar_blob IS NULL THEN 0 ELSE 1 END AS has_avatar FROM users WHERE email = :email"), {"email": email}).mappings().first()
    return dict(row) if row else None


