def get_user_avatar(user_id: int) -> tuple[bytes, str] | None:
    with get_connection() as conn:
        row = conn.execute(text("SELECT avatar_blob, avatar_content_type FROM users WHERE id = :user_id"), {"user_id": user_id}).first()
    if not row or row[0] is None:
        return None
    return bytes(row[0]), str(row[1] or "image/jpeg")


def resolve_analytics_month(user_id: int, preferred: str | None = None) -> str:
    if preferred and len(preferred) == 7 and preferred[4] == "-":
        return preferred
    current = date.today().strftime("%Y-%m")
    with get_connection() as conn:
        exists = conn.execute(text("SELECT 1 FROM transactions WHERE user_id = :user_id AND date LIKE :month LIMIT 1"), {"user_id": user_id, "month": f"{current}%"}).first()
        latest = conn.execute(text("SELECT SUBSTR(date, 1, 7) AS month FROM transactions WHERE user_id = :user_id ORDER BY date DESC, id DESC LIMIT 1"), {"user_id": user_id}).mappings().first()
    return current if exists else (latest["month"] if latest else current)


def get_month_summary(user_id: int, month: str) -> dict[str, float]:
    with get_connection() as conn:
        row = conn.execute(text("SELECT COALESCE(SUM(CASE WHEN type = 'income' THEN amount ELSE 0 END), 0) AS total_income, COALESCE(SUM(CASE WHEN type = 'expense' THEN amount ELSE 0 END), 0) AS total_expense FROM transactions WHERE user_id = :user_id AND date LIKE :month"), {"user_id": user_id, "month": f"{month}%"}).mappings().one()
    income, expense = float(row["total_income"]), float(row["total_expense"])
    return {"total_income": income, "total_expense": expense, "total_balance": income - expense}


def get_expense_by_category(user_id: int, month: str) -> list[dict[str, Any]]:
    with get_connection() as conn:
        rows = conn.execute(text("SELECT category, SUM(amount) AS total FROM transactions WHERE user_id = :user_id AND type = 'expense' AND date LIKE :month GROUP BY category ORDER BY total DESC, LOWER(category)"), {"user_id": user_id, "month": f"{month}%"}).mappings().all()
    return [{"category": row["category"], "total": float(row["total"])} for row in rows]


def get_category_spent(user_id: int, category: str, month: str) -> float:
    with get_connection() as conn:
        total = conn.execute(text("SELECT COALESCE(SUM(amount), 0) FROM transactions WHERE user_id = :user_id AND type = 'expense' AND category = :category AND date LIKE :month"), {"user_id": user_id, "category": category, "month": f"{month}%"}).scalar_one()
    return float(total)


def list_budget_records(user_id: int) -> list[dict[str, Any]]:
    with get_connection() as conn:
        rows = conn.execute(text("SELECT id, category, monthly_limit FROM budgets WHERE user_id = :user_id ORDER BY LOWER(category)"), {"user_id": user_id}).mappings().all()
    return [dict(row) for row in rows]


def upsert_budget(*, user_id: int, category: str, monthly_limit: float) -> None:
    with get_connection() as conn:
        found = conn.execute(text("SELECT id FROM budgets WHERE user_id = :user_id AND category = :category"), {"user_id": user_id, "category": category}).first()
        if found:
            conn.execute(text("UPDATE budgets SET monthly_limit = :monthly_limit WHERE id = :id AND user_id = :user_id"), {"monthly_limit": monthly_limit, "id": found[0], "user_id": user_id})
        else:
            conn.execute(text("INSERT INTO budgets (user_id, category, monthly_limit) VALUES (:user_id, :category, :monthly_limit)"), {"user_id": user_id, "category": category, "monthly_limit": monthly_limit})


