def _build_filters(*, user_id: int, tx_type: str | None = None, category: str | None = None, month: str | None = None, q: str | None = None) -> tuple[str, dict[str, Any]]:
    clauses = ["user_id = :user_id"]
    params: dict[str, Any] = {"user_id": user_id}
    if tx_type in ("income", "expense"):
        clauses.append("type = :type")
        params["type"] = tx_type
    if category:
        clauses.append("category = :category")
        params["category"] = category
    if month and len(month) == 7:
        clauses.append("date LIKE :month")
        params["month"] = f"{month}%"
    if q:
        clauses.append("(description LIKE :query OR category LIKE :query)")
        params["query"] = f"%{q}%"
    return "WHERE " + " AND ".join(clauses), params


def list_transactions(*, user_id: int, tx_type: str | None = None, category: str | None = None, month: str | None = None, q: str | None = None, limit: int = 50) -> list[dict[str, Any]]:
    where, params = _build_filters(user_id=user_id, tx_type=tx_type, category=category, month=month, q=q)
    params["limit"] = limit
    with get_connection() as conn:
        rows = conn.execute(text(f"SELECT id, type, amount, category, description, date, created_at FROM transactions {where} ORDER BY date DESC, id DESC LIMIT :limit"), params).mappings().all()
    result = []
    for row in rows:
        item = dict(row)
        item["amount"] = float(item["amount"])
        if hasattr(item["created_at"], "isoformat"):
            item["created_at"] = item["created_at"].isoformat(sep=" ")
        result.append(item)
    return result


def get_recent_transactions(user_id: int, limit: int = 10) -> list[dict[str, Any]]:
    return list_transactions(user_id=user_id, limit=limit)


def get_transaction(user_id: int, tx_id: int) -> dict[str, Any] | None:
    with get_connection() as conn:
        row = conn.execute(text("SELECT id, type, amount, category, description, date, created_at FROM transactions WHERE id = :id AND user_id = :user_id"), {"id": tx_id, "user_id": user_id}).mappings().first()
    if not row:
        return None
    item = dict(row)
    item["amount"] = float(item["amount"])
    if hasattr(item["created_at"], "isoformat"):
        item["created_at"] = item["created_at"].isoformat(sep=" ")
    return item


def create_transaction(*, user_id: int, tx_type: str, amount: float, category: str, description: str, date: str) -> int:
    with get_connection() as conn:
        statement = "INSERT INTO transactions (user_id, type, amount, category, description, date) VALUES (:user_id, :type, :amount, :category, :description, :date)"
        params = {"user_id": user_id, "type": tx_type, "amount": amount, "category": category, "description": description, "date": date}
        if conn.dialect.name == "postgresql":
            return int(conn.execute(text(statement + " RETURNING id"), params).scalar_one())
        return int(conn.execute(text(statement), params).lastrowid)


def update_transaction(user_id: int, tx_id: int, *, tx_type: str, amount: float, category: str, description: str, date: str) -> bool:
    with get_connection() as conn:
        result = conn.execute(text("UPDATE transactions SET type = :type, amount = :amount, category = :category, description = :description, date = :date WHERE id = :id AND user_id = :user_id"), {"type": tx_type, "amount": amount, "category": category, "description": description, "date": date, "id": tx_id, "user_id": user_id})
        return result.rowcount > 0


def delete_transaction(user_id: int, tx_id: int) -> bool:
    with get_connection() as conn:
        result = conn.execute(text("DELETE FROM transactions WHERE id = :id AND user_id = :user_id"), {"id": tx_id, "user_id": user_id})
        return result.rowcount > 0


def get_used_categories(user_id: int) -> list[str]:
    with get_connection() as conn:
        rows = conn.execute(text("SELECT DISTINCT category FROM transactions WHERE user_id = :user_id ORDER BY 1"), {"user_id": user_id}).scalars().all()
    return list(dict.fromkeys([*DEFAULT_CATEGORIES, *rows]))
